export function pickRandomThinkingWord(exclude?: string): string {
  const words: readonly string[] = AGENT_THINKING_WORDS;
  if (words.length === 0) {
    return "thinking";
  }
  if (words.length === 1) {
    return words[0];
  }
  let next = exclude ?? "";
  while (next === exclude) {
    next = words[Math.floor(Math.random() * words.length)] ?? "thinking";
  }
  return next;
}
